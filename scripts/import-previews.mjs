// Turns a style-previews.json exported from the app ("Export for the app" in
// the Style previews sheet) into web/src/preview-pack.ts, so the thumbnails
// ship with the web app and the plugin.
//
//   node scripts/import-previews.mjs path/to/style-previews.json

import { readFileSync, writeFileSync } from "node:fs";

const file = process.argv[2];
if (!file) {
  console.error("Usage: node scripts/import-previews.mjs style-previews.json");
  process.exit(1);
}
const json = JSON.parse(readFileSync(file, "utf8"));
if (json.kind !== "style-previews" || typeof json.tiles !== "object") {
  console.error("That file is not a style previews export.");
  process.exit(1);
}
const entries = Object.entries(json.tiles).filter(
  ([k, v]) => /^(ext|int|air):[a-z0-9-]+$/.test(k) && typeof v === "string" && v.startsWith("data:image/jpeg;base64,"),
);
const body = entries.map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`).join("\n");
writeFileSync(
  new URL("../web/src/preview-pack.ts", import.meta.url),
  `// Style preview thumbnails that ship with the app, keyed like "int:japandi".
// Generated by scripts/import-previews.mjs from a style-previews.json file
// exported in the app (${json.model ?? "unknown model"}, ${json.createdAt ?? "undated"}). Do not edit by hand.

export const PREVIEW_PACK: Record<string, string> = {
${body}
};
`,
);
const kb = Math.round(entries.reduce((n, [, v]) => n + v.length, 0) / 1024);
console.log(`Wrote ${entries.length} previews (${kb} KB) to web/src/preview-pack.ts`);
